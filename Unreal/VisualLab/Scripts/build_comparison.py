"""Editor-only import/lighting comparison. Does not port Unity gameplay or saves."""
import json
import os
import unreal

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "SourceAssets")
TOOLS = unreal.AssetToolsHelpers.get_asset_tools()
EDIT = unreal.MaterialEditingLibrary
LIB = unreal.EditorLevelLibrary
ASSETS = unreal.EditorAssetLibrary

def import_file(path, folder, name, mesh=False):
    task = unreal.AssetImportTask()
    task.filename = path
    task.destination_path = folder
    task.destination_name = name
    task.automated = True
    task.save = True
    task.replace_existing = True
    if mesh:
        options = unreal.FbxImportUI()
        options.import_mesh = True
        options.import_materials = False
        options.import_textures = False
        options.import_as_skeletal = False
        options.automated_import_should_detect_type = False
        options.mesh_type_to_import = unreal.FBXImportType.FBXIT_STATIC_MESH
        data = options.static_mesh_import_data
        data.combine_meshes = True
        data.convert_scene = False
        data.convert_scene_unit = False
        data.generate_lightmap_u_vs = True
        task.options = options
    TOOLS.import_asset_tasks([task])
    values = task.get_editor_property("imported_object_paths")
    if not values:
        raise RuntimeError("No imported asset for " + path)
    return ASSETS.load_asset(values[0])

def material(name, rgb, texture=None, roughness=0.7):
    path = "/Game/VisualLab/Materials/" + name
    mat = ASSETS.load_asset(path) if ASSETS.does_asset_exist(path) else None
    if mat:
        return mat  # Preserve material edits and compiled shader identities on rebuild.
    if not mat:
        mat = TOOLS.create_asset(name, "/Game/VisualLab/Materials", unreal.Material, unreal.MaterialFactoryNew())
    EDIT.delete_all_material_expressions(mat)
    mat.set_editor_property("two_sided", True)
    color = EDIT.create_material_expression(mat, unreal.MaterialExpressionConstant3Vector)
    color.set_editor_property("constant", unreal.LinearColor(rgb[0], rgb[1], rgb[2], 1.0))
    output = color
    if texture:
        sample = EDIT.create_material_expression(mat, unreal.MaterialExpressionTextureSample)
        sample.set_editor_property("texture", texture)
        output = EDIT.create_material_expression(mat, unreal.MaterialExpressionMultiply)
        EDIT.connect_material_expressions(color, "", output, "A")
        EDIT.connect_material_expressions(sample, "RGB", output, "B")
    EDIT.connect_material_property(output, "", unreal.MaterialProperty.MP_BASE_COLOR)
    value = EDIT.create_material_expression(mat, unreal.MaterialExpressionConstant)
    value.set_editor_property("r", roughness)
    EDIT.connect_material_property(value, "", unreal.MaterialProperty.MP_ROUGHNESS)
    EDIT.recompile_material(mat)
    ASSETS.save_loaded_asset(mat)
    return mat

def mesh_actor(name, mesh, xyz, scale, mat=None, yaw=0):
    actor = LIB.spawn_actor_from_class(unreal.StaticMeshActor, unreal.Vector(*xyz), unreal.Rotator(yaw=yaw))
    actor.set_actor_label(name)
    actor.set_actor_scale3d(unreal.Vector(*scale))
    comp = actor.static_mesh_component
    comp.set_static_mesh(mesh)
    if mat:
        comp.set_material(0, mat)
    return actor

if not os.path.exists(os.path.join(SOURCE, "Marty.obj")):
    raise RuntimeError("Run Unity VisualLabExport.Export first; SourceAssets missing")

MAP_PATH = "/Game/VisualLab/Comparison"
if ASSETS.does_asset_exist(MAP_PATH):
    if not LIB.load_level(MAP_PATH):
        raise RuntimeError("Cannot load the dedicated comparison map")
    # This map is generated by this script. Rebuild only this owned scene.
    for existing in LIB.get_all_level_actors():
        if existing.get_class().get_name() not in ("WorldSettings", "Brush"):
            LIB.destroy_actor(existing)
elif not LIB.new_level(MAP_PATH):
    raise RuntimeError("Cannot create comparison map")
cube = ASSETS.load_asset("/Engine/BasicShapes/Cube.Cube")
wood = material("WarmWood", (0.19, 0.095, 0.042), roughness=0.58)
plaster = material("CreamPlaster", (0.66, 0.60, 0.48), roughness=0.9)
blue = material("BlueBlanket", (0.035, 0.085, 0.20), roughness=0.95)
mesh_actor("Floor", cube, (0, 0, -8), (10, 9, 0.16), wood)
mesh_actor("Back wall", cube, (430, 0, 180), (0.16, 9, 3.6), plaster)
mesh_actor("Side wall", cube, (0, 450, 180), (9, 0.16, 3.6), plaster)
mesh_actor("Blue blanket platform", cube, (70, 0, 8), (2.5, 5.8, 0.16), blue)

for name, y in (("Marty", -170), ("Lakitu", 0), ("Rio", 170)):
    with open(os.path.join(SOURCE, name + ".json"), encoding="utf-8-sig") as stream:
        spec = json.load(stream)
    mesh = import_file(os.path.join(SOURCE, name + ".obj"), "/Game/VisualLab/Pets", name, True)
    mapped = {}
    for entry in spec["materials"]:
        texture = None
        if entry["texture"]:
            texture = import_file(os.path.join(SOURCE, entry["texture"]), "/Game/VisualLab/Textures", name + "_" + entry["key"])
        color = entry["color"]
        mapped[entry["key"]] = material(name + "_" + entry["key"], (color["r"], color["g"], color["b"]), texture)
    slots = mesh.get_editor_property("static_materials")
    for index, slot in enumerate(slots):
        key = str(slot.material_slot_name)
        if key not in mapped and index < len(spec["materials"]):
            key = spec["materials"][index]["key"]
        if key in mapped:
            mesh.set_material(index, mapped[key])
    ASSETS.save_loaded_asset(mesh)
    mesh_actor(name + " | static comparison", mesh, (70, y, 16), (1, 1, 1), yaw=180)

